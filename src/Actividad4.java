public void leerArchivoCSV(String ruta) {
    String linea;
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    
    modelo.setRowCount(0); 

    try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
        while ((linea = br.readLine()) != null) {
            String[] datos = linea.split(",");
            
            
            int id = Integer.parseInt(datos[0]);
            double largo = Double.parseDouble(datos[1]);
            double ancho = Double.parseDouble(datos[2]);
            double precioM2 = Double.parseDouble(datos[3]);

       
            double area = largo * ancho;
            double precioBase = area * precioM2;
            double desc = (area > 400) ? precioBase * 0.10 : 0;
            double total = precioBase - desc;

         
            modelo.addRow(new Object[]{id, largo, ancho, precioBase, desc, total});
            
            
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "hubo un error: " + e.getMessage());
    }
}   




