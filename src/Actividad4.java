    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
        String id = JOptionPane.showInputDialog("Ingrese ID:");
        String largo = JOptionPane.showInputDialog("Largo del terreno:");
        String ancho = JOptionPane.showInputDialog("Ancho del terreno:");
        String precio = JOptionPane.showInputDialog("Precio por m2:");

        if (id != null && largo != null && ancho != null && precio != null) {
            double L = Double.parseDouble(largo);
            double A = Double.parseDouble(ancho);
            double P = Double.parseDouble(precio);
            double area = L * A;
            double total = area * P; 

          
            DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
            Object[] nuevaFila = {id, L, A, P, area, total};
            modelo.addRow(nuevaFila);

           
            listaTerrenos.add(new Object[]{id, L, A, P});

         
            guardarEnArchivo();
            
            JOptionPane.showMessageDialog(this, "Terreno agregado y guardado en CSV");
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error en los datos");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:}
int filaVisual = jTable1.getSelectedRow();
    if (filaVisual != -1) {
        int indiceReal = jTable1.convertRowIndexToModel(filaVisual);
        
        
        Object[] datoEliminado = listaTerrenos.get(indiceReal);
        papelera.push(datoEliminado);
        rehacerStack.clear(); 
        
        listaTerrenos.remove(indiceReal);
        ((DefaultTableModel)jTable1.getModel()).removeRow(filaVisual);
        
        guardarEnArchivo();
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
    int filaVisual = jTable1.getSelectedRow();
    if (filaVisual != -1) {
        int indiceReal = jTable1.convertRowIndexToModel(filaVisual);
        
        String precioViejo = jTable1.getValueAt(filaVisual, 3).toString();
        String nuevoPrecio = JOptionPane.showInputDialog(this, "Nuevo precio por m2:", precioViejo);

        if (nuevoPrecio != null) {
            jTable1.setValueAt(nuevoPrecio, filaVisual, 3);
            
            listaTerrenos.get(indiceReal)[3] = Double.parseDouble(nuevoPrecio);

            guardarEnArchivo();
            JOptionPane.showMessageDialog(this, "Precio actualizado ");
        }
    } else {
        JOptionPane.showMessageDialog(this, "Selecciona un terreno primero");
    }
    }

