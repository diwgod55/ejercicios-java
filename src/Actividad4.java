    private void btnCargarCSVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarCSVActionPerformed
        // TODO add your handling code here:
        
       
  javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
    selector.setCurrentDirectory(new java.io.File("datos"));
    
    if (selector.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
        String ruta = selector.getSelectedFile().getAbsolutePath();
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
       
        modelo.setRowCount(0);
        listaTerrenos.clear(); 
        
        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                String[] d = linea.split(",");
                if (d.length >= 4) {
                   
                    String id = d[0];
                    double largo = Double.parseDouble(d[1]);
                    double ancho = Double.parseDouble(d[2]);
                    double precio = Double.parseDouble(d[3]);
                    
                   
                    double area = largo * ancho;
                    double subtotal = area * precio;
                    double desc = (area > 400) ? subtotal * 0.10 : 0;
                    double total = subtotal - desc;

                   
                    Object[] filaData = {id, largo, ancho, precio, area, total};
                    listaTerrenos.add(filaData);

                  
                    modelo.addRow(filaData);
                }
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Datos cargados en tabla y ArrayList");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "cargando el CSV: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnCargarCSVActionPerformed

