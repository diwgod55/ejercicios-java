    private void btnUndoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUndoActionPerformed
        // TODO add your handling code here:
       if (!papelera.isEmpty()) {
        Object[] recuperado = papelera.pop();
        rehacerStack.push(recuperado);
        
        listaFactura.add(recuperado);
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.addRow(recuperado);
        
        guardarEnArchivo();
    }
    }//GEN-LAST:event_btnUndoActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String texto = txtBuscar.getText();
    if (texto.trim().isEmpty()) {
        sorter.setRowFilter(null);
    } else {
        sorter.setRowFilter(RowFilter.regexFilter("(?i)" + texto));
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnRehacerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRehacerActionPerformed
        // TODO add your handling code here:
        if (!rehacerStack.isEmpty()) {
        Object[] aBorrar = rehacerStack.pop();
        papelera.push(aBorrar);
        
        listaFactura.remove(aBorrar);
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        for (int i = 0; i < modelo.getRowCount(); i++) {
            if (modelo.getValueAt(i, 0).equals(aBorrar[0])) {
                modelo.removeRow(i);
                break;
            }
        }
        
        guardarEnArchivo();
    }
    }//GEN-LAST:event_btnRehacerActionPerformed
public void leerFacturaCSV(String ruta) {
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    modelo.setRowCount(0);
   try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
        String linea;
        while ((linea = br.readLine()) != null) {
            String[] d = linea.split(",");
            int id = Integer.parseInt(d[0].trim());
            String art = d[1].trim();
            int cant = Integer.parseInt(d[2].trim());
            double precio = Double.parseDouble(d[3].trim());
            double totalArt = cant * precio;

            modelo.addRow(new Object[]{id, art, cant, precio, totalArt});
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}


