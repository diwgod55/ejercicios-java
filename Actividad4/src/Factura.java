private void guardarEnArchivo() {
    try {
        java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter("facturas.csv"));
        
        for (Object[] linea : listaFactura) {
            // Solo usamos hasta el índice 3 si el tamaño es 4 jaja
            pw.println(linea[0] + "," + linea[1] + "," + linea[2] + "," + linea[3]);
        }
        
        pw.close();
    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
    }
}

