    private void btnFacturaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFacturaActionPerformed
 JTextField idF = new JTextField();
    JTextField artF = new JTextField();
    JTextField cantF = new JTextField();
    JTextField precF = new JTextField();

    Object[] formulario = {"ID:", idF, "Artículo:", artF, "Cantidad:", cantF, "Precio:", precF};
    int opt = JOptionPane.showConfirmDialog(null, formulario, "Agregar a Factura", JOptionPane.OK_CANCEL_OPTION);

    if (opt == JOptionPane.OK_OPTION) {
        try {
            double totalFila = Integer.parseInt(cantF.getText()) * Double.parseDouble(precF.getText());
            
            DefaultTableModel mod = (DefaultTableModel) jTable1.getModel();
            mod.addRow(new Object[]{idF.getText(), artF.getText(), cantF.getText(), precF.getText(), totalFila});

         
            listaFactura.add(new Object[]{idF.getText(), artF.getText(), cantF.getText(), precF.getText()});
            
            JOptionPane.showMessageDialog(this, "Agregado");
        } catch (Exception e) { JOptionPane.showMessageDialog(this, "Revisa los números"); }
    }
    }//GEN-LAST:event_btnFacturaActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
int filaVisual = jTable1.getSelectedRow();
    if (filaVisual != -1) {
        int indiceReal = jTable1.convertRowIndexToModel(filaVisual);
        Object[] datoEliminado = listaFactura.get(indiceReal);
        
        papelera.push(datoEliminado);
        rehacerStack.clear(); 
        
        listaFactura.remove(indiceReal);
        ((DefaultTableModel)jTable1.getModel()).removeRow(filaVisual);
        guardarEnArchivo();
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();
    if (fila >= 0) {
        try {
            String art = javax.swing.JOptionPane.showInputDialog(this, "Articulo:", jTable1.getValueAt(fila, 1));
            String cantStr = javax.swing.JOptionPane.showInputDialog(this, "Cantidad:", jTable1.getValueAt(fila, 2));
            String precioStr = javax.swing.JOptionPane.showInputDialog(this, "Precio Unitario:", jTable1.getValueAt(fila, 3));

            if (art == null || cantStr == null || precioStr == null) return;

            int cant = Integer.parseInt(cantStr);
            double precioU = Double.parseDouble(precioStr);
            
            double precioTotalArt = cant * precioU;

            jTable1.setValueAt(art, fila, 1);
            jTable1.setValueAt(cant, fila, 2);
            jTable1.setValueAt(precioU, fila, 3);
            jTable1.setValueAt(precioTotalArt, fila, 4);

            double nuevoSubtotal = 0;
            for (int i = 0; i < jTable1.getRowCount(); i++) {
                nuevoSubtotal += Double.parseDouble(jTable1.getValueAt(i, 4).toString());
            }

            double nuevoImpuesto = nuevoSubtotal * 0.16;
            double nuevoTotalG = nuevoSubtotal + nuevoImpuesto;

            lblSubtotal.setText("SUBTOTAL: $" + nuevoSubtotal);
            lblImpuesto.setText("IVA (16%): $" + nuevoImpuesto);
            lblTotal.setText("TOTAL: $" + nuevoTotalG);

            javax.swing.JOptionPane.showMessageDialog(this, "Factura actualizada");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error en los datos");
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una fila primero");
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnCargarCSVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarCSVActionPerformed
        // TODO add your handling code here:
  javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
    selector.setCurrentDirectory(new java.io.File("datos"));
    
    if (selector.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
        String ruta = selector.getSelectedFile().getAbsolutePath();
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        
        modelo.setRowCount(0);
        listaFactura.clear(); 

        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                String[] d = linea.split(",");
                if (d.length >= 4) {
                    String id = d[0].trim();
                    String art = d[1].trim();
                    int cant = Integer.parseInt(d[2].trim());
                    double precio = Double.parseDouble(d[3].trim());
                    double totalFila = cant * precio;

                    listaFactura.add(new Object[]{id, art, String.valueOf(cant), String.valueOf(precio)});
                    
                 
                    modelo.addRow(new Object[]{id, art, cant, precio, totalFila});
                }
            }
            JOptionPane.showMessageDialog(this, "Factura cargada completa");
        } catch (Exception e) { JOptionPane.showMessageDialog(this, "Error: " + e.getMessage()); }
    }
    }//GEN-LAST:event_btnCargarCSVActionPerformed

    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
      
    double subtotal = 0;
    for (int i = 0; i < jTable1.getRowCount(); i++) {
        subtotal += Double.parseDouble(jTable1.getValueAt(i, 4).toString());
    }
    double itbis = subtotal * itbisPorcentaje;
    double total = subtotal + itbis;

    lblSubtotal.setText("Subtotal: $" + String.format("%.2f", subtotal));
    lblImpuesto.setText("ITBIS (18%): $" + String.format("%.2f", itbis));
    lblTotal.setText("Total: $" + String.format("%.2f", total));
    
    JOptionPane.showMessageDialog(this, "¡Totales calculados!, jaja");
    }//GEN-LAST:event_btnCalcularActionPerformed

