    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
int filaVisual = jTable1.getSelectedRow();
    if (filaVisual != -1) {
        int indiceReal = jTable1.convertRowIndexToModel(filaVisual);
        Object[] datoEliminado = listaNotas.get(indiceReal);
        
        papelera.push(datoEliminado);
        rehacerStack.clear(); 
        
        listaNotas.remove(indiceReal);
        ((DefaultTableModel)jTable1.getModel()).removeRow(filaVisual);
        
        guardarCalificacionesCSV();
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
       int fila = jTable1.getSelectedRow();
    
    
    if (fila != -1) {
        
        String idActual = jTable1.getValueAt(fila, 0).toString();
        String nomActual = jTable1.getValueAt(fila, 1).toString();
        String n1Actual = jTable1.getValueAt(fila, 2).toString();
        String n2Actual = jTable1.getValueAt(fila, 3).toString();
        String n3Actual = jTable1.getValueAt(fila, 4).toString();
        String n4Actual = jTable1.getValueAt(fila, 5).toString();

        JTextField txtNom = new JTextField(nomActual);
        JTextField txtN1 = new JTextField(n1Actual);
        JTextField txtN2 = new JTextField(n2Actual);
        JTextField txtN3 = new JTextField(n3Actual);
        JTextField txtN4 = new JTextField(n4Actual);

        Object[] mensaje = {
            "Estudiante: " + idActual,
            "Nombre:", txtNom,
            "Nota 1:", txtN1,
            "Nota 2:", txtN2,
            "Nota 3:", txtN3,
            "Nota 4:", txtN4
        };

       
        int opcion = JOptionPane.showConfirmDialog(null, mensaje, "Actualizar Calificaciones", JOptionPane.OK_CANCEL_OPTION);

        if (opcion == JOptionPane.OK_OPTION) {
            try {
             
                String nuevoNom = txtNom.getText();
                double n1 = Double.parseDouble(txtN1.getText());
                double n2 = Double.parseDouble(txtN2.getText());
                double n3 = Double.parseDouble(txtN3.getText());
                double n4 = Double.parseDouble(txtN4.getText());
                double nuevoProm = (n1 + n2 + n3 + n4) / 4.0;

             
                jTable1.setValueAt(nuevoNom, fila, 1);
                jTable1.setValueAt(n1, fila, 2);
                jTable1.setValueAt(n2, fila, 3);
                jTable1.setValueAt(n3, fila, 4);
                jTable1.setValueAt(n4, fila, 5);
                jTable1.setValueAt(String.format("%.2f", nuevoProm), fila, 6);

                Object[] filaActualizada = {idActual, nuevoNom, n1, n2, n3, n4};
                listaNotas.set(fila, filaActualizada);

                JOptionPane.showMessageDialog(this, "Datos de " + nuevoNom + " actualizados");

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "metiste una letra donde va un número");
            }
        }
    } else {
        JOptionPane.showMessageDialog(this, "Selecciona al estudiante que vas a editar");
    }
        
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnCargarCSVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarCSVActionPerformed
       javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
    selector.setCurrentDirectory(new java.io.File("datos"));
    
    if (selector.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
        String ruta = selector.getSelectedFile().getAbsolutePath();
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        
        modelo.setRowCount(0);
        listaNotas.clear(); 

        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                String[] d = linea.split(",");
               
                double n1 = Double.parseDouble(d[2]);
                double n2 = Double.parseDouble(d[3]);
                double n3 = Double.parseDouble(d[4]);
                double n4 = Double.parseDouble(d[5]);
                double prom = (n1 + n2 + n3 + n4) / 4.0;

               
                listaNotas.add(new Object[]{d[0], d[1], d[2], d[3], d[4], d[5]});

                
                modelo.addRow(new Object[]{d[0], d[1], d[2], d[3], d[4], d[5], String.format("%.2f", prom)});
            }
            JOptionPane.showMessageDialog(this, "Notas cargadas nítido");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "cargando: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnCargarCSVActionPerformed

