public void importarNotas(String ruta) {
    String linea;
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    modelo.setRowCount(0);

    try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
        while ((linea = br.readLine()) != null) {
            
            String[] d = linea.split(",");
            
            if (d.length >= 6) {
                int id = Integer.parseInt(d[0].trim());
                String alumno = d[1].trim();
                double n1 = Double.parseDouble(d[2].trim());
                double n2 = Double.parseDouble(d[3].trim());
                double n3 = Double.parseDouble(d[4].trim());
                double n4 = Double.parseDouble(d[5].trim());

                
                double promedio = (n1 + n2 + n3 + n4) / 4.0;

              
                modelo.addRow(new Object[]{id, alumno, n1, n2, n3, n4, String.format("%.2f", promedio)});
                
              
            }
        }
        javax.swing.JOptionPane.showMessageDialog(this, "¡Notas cargadas y promedios calculados!");
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "hubo un problema: " + e.getMessage());
    }
}
public void guardarCalificacionesCSV() {
    String ruta = "datos/actividad-6-datos-ejer4.csv";
    try (java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter(ruta))) {
        for (Object[] fila : listaNotas) {
           
            pw.println(fila[0] + "," + fila[1] + "," + fila[2] + "," + fila[3] + "," + fila[4] + "," + fila[5]);
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
    }
}


