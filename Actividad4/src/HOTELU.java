    private void guardarEnArchivo() {
    try {
        java.io.PrintWriter pw = new java.io.PrintWriter(new java.io.FileWriter("datos-hotel.csv"));
        for (Object[] fila : listaHospedaje) {
            pw.println(fila[0] + "," + fila[1] + "," + fila[2] + "," + fila[3]);
        }
        pw.close();
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el archivo jaja");
    }
}

