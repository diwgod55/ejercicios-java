    private void btnHospedajeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHospedajeActionPerformed
                // TODO add your handling code here:
      JTextField txtId = new JTextField();
    JTextField txtCliente = new JTextField();
    JTextField txtDias = new JTextField();
    JTextField txtPrecio = new JTextField();

    Object[] formulario = {
        "ID del Hospedaje:", txtId,
        "Nombre del Cliente:", txtCliente,
        "Días de Estancia:", txtDias,
        "Precio por Noche ($):", txtPrecio
    };

  
    int opcion = JOptionPane.showConfirmDialog(null, formulario, "Nuevo Registro - HOTELU", JOptionPane.OK_CANCEL_OPTION);

    if (opcion == JOptionPane.OK_OPTION) {
        try {
           
            String id = txtId.getText();
            String cliente = txtCliente.getText();
            int dias = Integer.parseInt(txtDias.getText());
            double precio = Double.parseDouble(txtPrecio.getText());

           
            double subtotal = dias * precio;
           
            double descuento = (dias > 5) ? subtotal * 0.05 : 0.0;
            double total = subtotal - descuento;

           
            DefaultTableModel modelo = (DefaultTableModel) Tabla1.getModel();
            modelo.addRow(new Object[]{
                id, 
                cliente, 
                dias, 
                precio, 
                subtotal, 
                descuento, 
                total
            });

            
            listaHospedaje.add(new Object[]{id, cliente, String.valueOf(dias), String.valueOf(precio)});

            JOptionPane.showMessageDialog(this, "¡Hospedaje de " + cliente + " agregado.");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "verifica los numeros. No me pongas letras en los días o el precio");
        }
    }
    }//GEN-LAST:event_btnHospedajeActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
 int filaVisual = Tabla1.getSelectedRow();
    if (filaVisual != -1) {
        int indiceReal = Tabla1.convertRowIndexToModel(filaVisual);
        Object[] datoEliminado = listaHospedaje.get(indiceReal);
        
        papelera.push(datoEliminado);
        rehacerStack.clear(); 
        
        listaHospedaje.remove(indiceReal);
        ((DefaultTableModel)Tabla1.getModel()).removeRow(filaVisual);
        
        guardarEnArchivo();
    }
        
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int fila = Tabla1.getSelectedRow();
    if (fila != -1) {
       
        String id = Tabla1.getValueAt(fila, 0).toString();
        String clienteActual = Tabla1.getValueAt(fila, 1).toString();
        String diasActual = Tabla1.getValueAt(fila, 2).toString();
        String precioActual = Tabla1.getValueAt(fila, 3).toString();

        JTextField txtCliente = new JTextField(clienteActual);
        JTextField txtDias = new JTextField(diasActual);
        JTextField txtPrecio = new JTextField(precioActual);

        Object[] formulario = {
            "ID: " + id,
            "Nombre Cliente:", txtCliente,
            "Días de Estancia:", txtDias,
            "Precio por Día:", txtPrecio
        };

        int opcion = JOptionPane.showConfirmDialog(null, formulario, "Actualizar Hospedaje", JOptionPane.OK_CANCEL_OPTION);

        if (opcion == JOptionPane.OK_OPTION) {
            try {
                String nCliente = txtCliente.getText();
                int nDias = Integer.parseInt(txtDias.getText());
                double nPrecio = Double.parseDouble(txtPrecio.getText());
                
                double nSubtotal = nDias * nPrecio;
                double nDesc = (nDias > 5) ? nSubtotal * 0.05 : 0.0;
                double nTotal = nSubtotal - nDesc;

               
                Tabla1.setValueAt(nCliente, fila, 1);
                Tabla1.setValueAt(nDias, fila, 2);
                Tabla1.setValueAt(nPrecio, fila, 3);
                Tabla1.setValueAt(nSubtotal, fila, 4);
                Tabla1.setValueAt(nDesc, fila, 5);
                Tabla1.setValueAt(nTotal, fila, 6);

               
                listaHospedaje.set(fila, new Object[]{id, nCliente, String.valueOf(nDias), String.valueOf(nPrecio)});
                
                JOptionPane.showMessageDialog(this, "Hospedaje actualizado");
            } catch (Exception e) { JOptionPane.showMessageDialog(this, "Pon números"); }
        }
    } else {
        JOptionPane.showMessageDialog(this, "Selecciona una fila");
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
       javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
    selector.setCurrentDirectory(new java.io.File("datos"));
    
    if (selector.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
        String ruta = selector.getSelectedFile().getAbsolutePath();
        DefaultTableModel modelo = (DefaultTableModel) Tabla1.getModel();
        modelo.setRowCount(0);
        listaHospedaje.clear(); 

        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                String[] d = linea.split(",");
              
                int dias = Integer.parseInt(d[2]);
                double precio = Double.parseDouble(d[3]);
                
                double subtotal = dias * precio;
                double desc = (dias > 5) ? subtotal * 0.05 : 0.0;
                double total = subtotal - desc;

                
                listaHospedaje.add(new Object[]{d[0], d[1], d[2], d[3]});
                
                modelo.addRow(new Object[]{d[0], d[1], d[2], d[3], subtotal, desc, total});
            }
        } catch (Exception e) { /* error */ }
    }
    }//GEN-LAST:event_btnCargarActionPerformed

