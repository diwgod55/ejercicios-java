    private void TrajeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TrajeActionPerformed
JTextField txtId = new JTextField();
    JTextField txtCliente = new JTextField();
    JTextField txtCant = new JTextField();
    JTextField txtPrecio = new JTextField();

    Object[] formulario = {
        "ID Venta:", txtId,
        "Nombre Cliente:", txtCliente,
        "Cantidad de Trajes:", txtCant,
        "Precio Unitario ($):", txtPrecio
    };

    int opcion = JOptionPane.showConfirmDialog(null, formulario, "Nueva Venta de Trajes", JOptionPane.OK_CANCEL_OPTION);

    if (opcion == JOptionPane.OK_OPTION) {
        try {
            String id = txtId.getText();
            String cliente = txtCliente.getText();
            int cant = Integer.parseInt(txtCant.getText());
            double precio = Double.parseDouble(txtPrecio.getText());

            
            double subtotal = cant * precio;
            double porcDesc = (cant > 3) ? 0.15 : 0.0;
            double desc = subtotal * porcDesc;
            double total = subtotal - desc;

         
            DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
            modelo.addRow(new Object[]{id, cliente, cant, (porcDesc * 100) + "%", precio, subtotal, total});

           
            listaTrajes.add(new Object[]{id, cliente, String.valueOf(cant), String.valueOf(precio)});
            
            JOptionPane.showMessageDialog(this, "¡Venta de " + cliente + "agregada");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "revisa esos números");
        }
    }
    }//GEN-LAST:event_TrajeActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
int filaVisual = jTable1.getSelectedRow();
    if (filaVisual != -1) {
        int indiceReal = jTable1.convertRowIndexToModel(filaVisual);
        Object[] datoEliminado = listaTrajes.get(indiceReal);
        
        papelera.push(datoEliminado);
        rehacerStack.clear(); 
        
        listaTrajes.remove(indiceReal);
        ((DefaultTableModel)jTable1.getModel()).removeRow(filaVisual);
        
        guardarTrajesEnCSV();
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    int filaVisual = jTable1.getSelectedRow();
    if (filaVisual != -1) {
        int indiceReal = jTable1.convertRowIndexToModel(filaVisual);
        
        String cantidadActual = jTable1.getValueAt(filaVisual, 2).toString();
        String nuevaCantidad = JOptionPane.showInputDialog(this, "Ingrese la nueva cantidad:", cantidadActual);

        if (nuevaCantidad != null) {
            try {
                double cant = Double.parseDouble(nuevaCantidad);
                double precioU = Double.parseDouble(listaTrajes.get(indiceReal)[4].toString());
                
                double nuevoSubtotal = cant * precioU;
                double porcDesc = (cant > 3) ? 0.15 : 0.0;
                double nuevoTotal = nuevoSubtotal - (nuevoSubtotal * porcDesc);

                jTable1.setValueAt(nuevaCantidad, filaVisual, 2);
                jTable1.setValueAt(nuevoTotal, filaVisual, 6);

                listaTrajes.get(indiceReal)[2] = cant;
                listaTrajes.get(indiceReal)[6] = nuevoTotal;

                guardarTrajesEnCSV();
                JOptionPane.showMessageDialog(this, "Registro actualizado correctamente.");
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Error: Ingrese un valor numérico válido.");
            }
        }
    } else {
        JOptionPane.showMessageDialog(this, "Seleccione un registro para actualizar.");
    } 
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnCargarTrajesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarTrajesActionPerformed
        
        javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
    selector.setCurrentDirectory(new java.io.File("datos"));
    
    if (selector.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
        String ruta = selector.getSelectedFile().getAbsolutePath();
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        
        
        modelo.setRowCount(0);
        listaTrajes.clear(); 
        
        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                
                String[] d = linea.split(",");
                
                if (d.length >= 4) {
                    
                    String id = d[0].trim();
                    String cliente = d[1].trim();
                    int cant = Integer.parseInt(d[2].trim());
                    double precio = Double.parseDouble(d[3].trim());

                   
                    double subtotal = cant * precio;
                    double porcDesc = (cant > 3) ? 0.15 : 0.0;
                    double desc = subtotal * porcDesc;
                    double total = subtotal - desc;

                   
                    listaTrajes.add(new Object[]{id, cliente, String.valueOf(cant), String.valueOf(precio)});

                    modelo.addRow(new Object[]{
                        id, 
                        cliente, 
                        cant, 
                        (porcDesc * 100) + "%", 
                        precio, 
                        subtotal, 
                        total
                    });
                }
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Datos cargados y listos en memoria");
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "hubo un error: " + e.getMessage());
        }
    } 
    }//GEN-LAST:event_btnCargarTrajesActionPerformed

