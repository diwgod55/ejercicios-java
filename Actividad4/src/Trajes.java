    public void leerCSV(String ruta) {
    String linea;
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    modelo.setRowCount(0); 

    try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(ruta))) {
        while ((linea = br.readLine()) != null) {
            String[] d = linea.split(",");
            
            if (d.length >= 4) {
                int id = Integer.parseInt(d[0].trim());
                String cliente = d[1].trim();
                int cantidad = Integer.parseInt(d[2].trim());
                double precioU = Double.parseDouble(d[3].trim());

                
                double subtotal = cantidad * precioU;
                double porcDesc = (cantidad > 3) ? 0.15 : 0.0; 
                double descuento = subtotal * porcDesc;
                double total = subtotal - descuento;

              
                modelo.addRow(new Object[]{
                    id, 
                    cliente, 
                    cantidad, 
                    (porcDesc * 100) + "%", 
                    precioU, 
                    subtotal, 
                    total
                });
            }
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Trajes importados con exito");
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "falló la lectura: " + e.getMessage());
    }
}
    
